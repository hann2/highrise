import chokidar from "chokidar";
import fs from "fs";
import { globSync } from "glob";
import path from "path";
import { resourceName } from "../src/core/resources/resourceName";

/*
 * Generates resources/resources.ts, a manifest of every asset in the resources
 * folder. The manifest is what makes assets available by name (with type
 * checking and autocomplete), and is what the preloader uses to know what to
 * load.
 *
 * Usage:
 *   tsx ./bin/generate-manifest.ts          # generate once
 *   tsx ./bin/generate-manifest.ts watch    # regenerate when files are added/removed
 */

const RESOURCES_FOLDER = path.resolve(__dirname, "../resources");
const MANIFEST_FILE = path.join(RESOURCES_FOLDER, "resources.ts");

const EXTENSIONS = {
  images: ["bmp", "gif", "jpg", "png", "svg"],
  sounds: ["flac", "mp3", "ogg", "wav"],
  fonts: ["ttf", "otf", "woff", "woff2"],
} as const;
type ResourceType = keyof typeof EXTENSIONS;
const RESOURCE_TYPES = Object.keys(EXTENSIONS) as ResourceType[];
const ALL_EXTENSIONS = RESOURCE_TYPES.flatMap((type) => EXTENSIONS[type]);

function generateManifest() {
  const fileNames = globSync(
    `${RESOURCES_FOLDER}/**/*.@(${ALL_EXTENSIONS.join("|")})`,
  ).sort();

  const sections: string[] = [];
  const collisions: string[] = [];

  for (const type of RESOURCE_TYPES) {
    const extensions: readonly string[] = EXTENSIONS[type];
    const nameToFile = new Map<string, string>();

    for (const fileName of fileNames) {
      if (!extensions.includes(path.extname(fileName).slice(1))) {
        continue;
      }
      const name = resourceName(fileName);
      const relativePath =
        "./" + path.relative(RESOURCES_FOLDER, fileName).replaceAll("\\", "/");
      const existing = nameToFile.get(name);
      if (existing) {
        collisions.push(`${type}.${name}: ${existing} and ${relativePath}`);
      }
      nameToFile.set(name, relativePath);
    }

    const entries = [...nameToFile.entries()]
      .map(
        ([name, file]) => `  ${JSON.stringify(name)}: require("url:${file}"),`,
      )
      .join("\n");
    const typeName = type[0].toUpperCase() + type.slice(1, -1) + "Name";
    sections.push(
      `const ${type} = {\n${entries}\n};\nexport type ${typeName} = keyof typeof ${type};`,
    );
  }

  if (collisions.length > 0) {
    // Resources are referred to by name, so names have to be unique
    throw new Error(
      `Multiple resources would have the same name. Rename one of each:\n` +
        collisions.map((c) => ` - ${c}`).join("\n"),
    );
  }

  const content = [
    "// This file is autogenerated by bin/generate-manifest.ts",
    "// Do not modify it by hand. Any changes will be overwritten.",
    ...sections,
    `export const RESOURCES = { ${RESOURCE_TYPES.join(", ")} };`,
    "",
  ].join("\n");

  const previous = fs.existsSync(MANIFEST_FILE)
    ? fs.readFileSync(MANIFEST_FILE, "utf8")
    : undefined;
  if (previous !== content) {
    fs.writeFileSync(MANIFEST_FILE, content);
    console.log(`Updated ${path.relative(process.cwd(), MANIFEST_FILE)}`);
  }
}

function tryGenerateManifest() {
  try {
    generateManifest();
  } catch (e) {
    console.error((e as Error).message);
    return false;
  }
  return true;
}

if (process.argv[2] === "watch") {
  tryGenerateManifest();
  console.log(`Watching for resource changes in ${RESOURCES_FOLDER}`);
  chokidar
    .watch(RESOURCES_FOLDER, {
      ignoreInitial: true,
      ignored: (file, stats) =>
        !!stats?.isFile() &&
        !ALL_EXTENSIONS.includes(path.extname(file).slice(1) as any),
    })
    .on("add", tryGenerateManifest)
    .on("unlink", tryGenerateManifest);
} else if (!tryGenerateManifest()) {
  process.exit(1);
}
