/**
 * What a gun's generator (bin/gun-art/guns/<name>.ts) provides: its drawings, in its reference photo's pixels,
 * and how those become the game's art. The generator is the source; the SVGs it writes are committed output.
 */
import path from "path";
import type { PhotoScale, PickupFrame } from "./svg";
import { pickupTag, toMillimeters } from "./svg";

export const REPO = path.resolve(import.meta.dirname, "../../..");
/** Reference photos, kept locally and not committed (we don't own them): <name>/<file> */
export const REFERENCES = path.join(
  REPO,
  "assets/source/images/weapons/references",
);
/** Where pickups go, shipped as SVG */
export const PICKUPS = path.join(REPO, "resources/images/weapons");
/** Where the tools put the images they make */
export const OUTPUT = path.join(REPO, "tests/output/gun-art");

export interface ReferencePhoto {
  /** The file's name in REFERENCES/<gun>/ */
  readonly file: string;
  readonly width: number;
  readonly height: number;
  /** What it shows, and where it came from if known */
  readonly about: string;
}

export interface GunDrawing<Options = unknown> {
  /** The file name stem: <name>-pickup.svg */
  readonly name: string;
  /** The photo the side view is drawn over, in whose pixels it's drawn */
  readonly photo: ReferencePhoto;
  /** Other photos worth checking against (better lit, other angles) */
  readonly otherPhotos?: readonly ReferencePhoto[];
  readonly scale: PhotoScale;
  readonly frame: PickupFrame;
  /** The comment at the top of the pickup: what the gun is and how it's drawn */
  readonly comment: string;
  /** The side view, as a whole SVG in the photo's pixels, with options (colors, styles) changed */
  drawSide(options?: Options): string;
}

export function photoPath(
  gun: GunDrawing<any>,
  photo: ReferencePhoto = gun.photo,
): string {
  return path.join(REFERENCES, gun.name, photo.file);
}

export function pickupPath(gun: GunDrawing<any>): string {
  return path.join(PICKUPS, `${gun.name}-pickup.svg`);
}

/** The pickup's SVG: the side view in millimeters, framed */
export function pickupSvg<Options>(
  gun: GunDrawing<Options>,
  options?: Options,
): string {
  const generated =
    `\n  <!-- Generated by bin/gun-art/guns/${gun.name}.ts (npx tsx bin/gun-art/cli.ts build ${gun.name}): ` +
    "change that, not this -->";
  return (
    pickupTag(gun.frame, gun.scale) +
    generated +
    gun.comment +
    toMillimeters(gun.drawSide(options), gun.scale)
  );
}
